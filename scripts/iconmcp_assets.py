"""Fetch reviewed public IconMCP SVGs explicitly; normal checks/builds are offline."""
import argparse
import concurrent.futures
import hashlib
import json
from pathlib import Path
import re
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'design/icons/iconmcp'
MANIFEST = ASSETS / 'manifest.json'
ENDPOINT = 'https://iconmcp.com/mcp'


def validate_svg(svg):
    if len(svg.encode()) > 32768 or '<!DOCTYPE' in svg or '<!ENTITY' in svg:
        raise ValueError('Unsupported SVG document')
    root = ET.fromstring(svg)
    if root.tag != '{http://www.w3.org/2000/svg}svg' or root.get('viewBox') != '0 0 16 16':
        raise ValueError('Unexpected SVG grid')
    allowed = {'svg', 'g', 'path', 'line', 'polyline', 'polygon', 'circle', 'ellipse', 'rect'}
    for node in root.iter():
        if node.tag.split('}')[-1] not in allowed:
            raise ValueError('Unsupported SVG element')
        for key, value in node.attrib.items():
            if key.lower().startswith('on') or 'href' in key.lower() or 'url(' in value.lower():
                raise ValueError('SVG must be self-contained')


def read_manifest():
    manifest = json.loads(MANIFEST.read_text(encoding='utf-8'))
    if manifest['schema'] != 1 or manifest['source'] != ENDPOINT:
        raise ValueError('Unsupported icon manifest')
    for key, icon in manifest['icons'].items():
        if not re.fullmatch(r'[a-z][A-Za-z0-9]*', key) or not re.fullmatch(r'[a-z][a-z0-9-]{0,79}', icon['name']):
            raise ValueError('Invalid icon name')
    if not set(manifest['materialAliases'].values()) <= set(manifest['icons']):
        raise ValueError('Unknown icon alias')
    return manifest


def check_assets():
    manifest = read_manifest()
    for icon in manifest['icons'].values():
        raw = (ASSETS / (icon['name'] + '.svg')).read_bytes()
        validate_svg(raw.decode('utf-8'))
        if hashlib.sha256(raw).hexdigest() != icon['sha256']:
            raise ValueError('Icon digest mismatch: ' + icon['name'])
    return manifest


def fetch_icon(item, style):
    key, icon = item
    request = urllib.request.Request(ENDPOINT, data=json.dumps({
        'jsonrpc': '2.0', 'id': 1, 'method': 'tools/call',
        'params': {'name': 'get_icon', 'arguments': {'name': icon['name'], 'format': 'svg', **style}},
    }).encode(), headers={
        'Content-Type': 'application/json', 'Accept': 'application/json, text/event-stream',
        'User-Agent': 'Mozilla/5.0', 'MCP-Protocol-Version': '2025-03-26',
    })
    with urllib.request.urlopen(request, timeout=30) as response:
        result = json.loads(response.read(65536))['result']
    if result.get('isError'):
        raise ValueError('IconMCP rejected ' + icon['name'])
    svg = next(c['text'] for c in result['content'] if c.get('type') == 'text' and c['text'].startswith('<svg'))
    metadata = next(json.loads(c['text']) for c in result['content'] if c.get('type') == 'text' and c['text'].startswith('{'))
    if metadata['name'] != icon['name']:
        raise ValueError('IconMCP returned a different icon')
    validate_svg(svg)
    return key, svg.encode('utf-8'), metadata


def generate_catalog(manifest):
    lines = ["// Generated by scripts/iconmcp_assets.py; public, locally bundled SVGs.", "part of 'app_icons.dart';", '', 'abstract final class AppIcons {']
    for key, icon in manifest['icons'].items():
        direction = ', matchTextDirection: true' if icon.get('directional') else ''
        lines.append(f"  static const {key} = AppIconData('{icon['name']}'{direction});")
    lines += ['', '  static const values = <AppIconData>[']
    lines += ['    ' + key + ',' for key in manifest['icons']]
    lines += ['  ];', '}', '']
    (ROOT / 'mobile/lib/ui/app_icons.g.dart').write_text('\n'.join(lines), encoding='utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--fetch', action='store_true', help='explicitly refresh reviewed icons and digests from IconMCP')
    args = parser.parse_args()
    manifest = read_manifest()
    if args.fetch:
        with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
            results = list(pool.map(lambda item: fetch_icon(item, manifest['style']), manifest['icons'].items()))
        # Do not replace any asset until every response has been validated.
        for key, raw, metadata in results:
            icon = manifest['icons'][key]
            (ASSETS / (icon['name'] + '.svg')).write_bytes(raw)
            icon.update(sha256=hashlib.sha256(raw).hexdigest(), label=metadata['label'], set=metadata['set'])
        MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        generate_catalog(manifest)
    check_assets()
    print(f"Verified {len(manifest['icons'])} local IconMCP SVGs; {'explicit fetch' if args.fetch else 'offline check'}.")


if __name__ == '__main__':
    main()
